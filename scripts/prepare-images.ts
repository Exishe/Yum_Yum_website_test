// Scans public/images and writes lib/images.generated.ts with the size and a
// tiny blurred placeholder for every photo. Originals are never modified.
// Run after adding photos: pnpm images
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import sharp from "sharp";

const root = join(process.cwd(), "public");
const exts = /\.(jpe?g|png|webp|avif)$/i;

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return name === "uploads" ? [] : walk(full);
    return exts.test(name) ? [full] : [];
  });
}

async function main() {
  const files = walk(join(root, "images")).sort();
  const entries: string[] = [];
  for (const file of files) {
    const img = sharp(file);
    const meta = await img.metadata();
    const blur = await sharp(file)
      .resize(12, 12, { fit: "inside" })
      .webp({ quality: 40 })
      .toBuffer();
    const key = "/" + relative(root, file).split(sep).join("/");
    entries.push(
      `  ${JSON.stringify(key)}: { w: ${meta.width}, h: ${meta.height}, blur: "data:image/webp;base64,${blur.toString("base64")}" },`,
    );
  }
  const out = `// Generated by scripts/prepare-images.ts. Do not edit by hand.\nexport const imageManifest: Record<string, { w: number; h: number; blur: string }> = {\n${entries.join("\n")}\n};\n`;
  writeFileSync(join(process.cwd(), "lib/images.generated.ts"), out);
  console.log(`Wrote ${entries.length} images to lib/images.generated.ts`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
